"""The prompts, ported from Google's ADK financial-advisor recipe.

https://github.com/google/adk-recipes/tree/main/python/agents/financial-advisor

What changed in the port, and why:

- ADK passes each analyst's report to the next through session-state keys
  (``output_key``). Here a tool writes its report to the conversation's working
  memory and the later tools read it there, so the coordinator is told that the
  reports are kept for it rather than told to manage keys.
- The analysts cannot prompt the user (they run as tools), so the lines telling
  them to ask for the risk attitude or the period are gone: the coordinator asks,
  and passes the answers in.
- The disclaimer is one constant, named once, quoted by every prompt that must
  show it. Its wording no longer names Google.
"""

